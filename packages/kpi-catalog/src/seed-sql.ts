import { CATALOG } from "./index.ts";
import { TEMPLATES } from "./templates.ts";

const text = (value: string) => `'${value.replaceAll("'", "''")}'`;
const list = (values: readonly string[]) =>
  values.length ? `array[${values.map(text).join(",")}]::text[]` : "'{}'::text[]";

/**
 * The SQL that loads the catalog into `kpi_catalog.*`.
 *
 * It is safe to run again: measures and KPIs are upserted, and templates are
 * replaced as a whole. Organisations that already used a template keep their
 * own copy, so reseeding never changes a customer's KPIs.
 */
export function seedSql(): string {
  const out: string[] = [
    "-- Generated by packages/kpi-catalog (npm run seed:sql). Do not edit by hand.",
    `-- ${CATALOG.kpis.length} KPIs, ${CATALOG.measures.length} measures, ${TEMPLATES.length} templates.`,
    "begin;",
  ];

  out.push("insert into kpi_catalog.measures(key,name,unit,description,rolls_up,domain) values");
  out.push(
    CATALOG.measures
      .map((m) => `(${text(m.key)},${text(m.name)},${text(m.unit)},${text(m.description)},${m.rollsUp},${text(m.domain)})`)
      .join(",\n"),
  );
  out.push(
    "on conflict (key) do update set name=excluded.name, unit=excluded.unit, description=excluded.description, rolls_up=excluded.rolls_up, domain=excluded.domain;",
  );

  out.push(
    "insert into kpi_catalog.kpis(id,name,description,domain,industries,formula,formula_text,unit,direction,measures,needs_history,sources,scope) values",
  );
  out.push(
    CATALOG.kpis
      .map(
        (k) =>
          `(${text(k.id)},${text(k.name)},${text(k.description)},${text(k.domain)},${list(k.industries)},${text(JSON.stringify(k.formula))}::jsonb,${text(k.formulaText)},${text(k.unit)},${text(k.direction)},${list(k.measures)},${k.needsHistory},${list(k.sources)},${text(k.scope)})`,
      )
      .join(",\n"),
  );
  out.push(
    "on conflict (id) do update set name=excluded.name, description=excluded.description, domain=excluded.domain, industries=excluded.industries, formula=excluded.formula, formula_text=excluded.formula_text, unit=excluded.unit, direction=excluded.direction, measures=excluded.measures, needs_history=excluded.needs_history, sources=excluded.sources, scope=excluded.scope;",
  );

  out.push(
    "delete from kpi_catalog.template_role_kpis;",
    "delete from kpi_catalog.template_roles;",
    "delete from kpi_catalog.templates;",
  );
  out.push("insert into kpi_catalog.templates(id,name,industry,description) values");
  out.push(
    TEMPLATES.map((t) => `(${text(t.id)},${text(t.name)},${text(t.industry)},${text(t.description)})`).join(",\n") + ";",
  );
  out.push("insert into kpi_catalog.template_roles(template_id,role_key,name,description,capabilities,position) values");
  out.push(
    TEMPLATES.flatMap((t) =>
      t.roles.map(
        (r, i) =>
          `(${text(t.id)},${text(r.key)},${text(r.name)},${text(r.description)},${list(r.capabilities)},${i})`,
      ),
    ).join(",\n") + ";",
  );
  out.push("insert into kpi_catalog.template_role_kpis(template_id,role_key,kpi_id,position) values");
  out.push(
    TEMPLATES.flatMap((t) =>
      t.roles.flatMap((r) =>
        r.kpis.map((id, i) => `(${text(t.id)},${text(r.key)},${text(id)},${i})`),
      ),
    ).join(",\n") + ";",
  );
  out.push("commit;", "");
  return out.join("\n");
}
