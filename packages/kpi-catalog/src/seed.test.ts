import { readFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
import { describe, expect, it } from "vitest";
import { seedSql } from "./seed-sql.ts";

describe("database seed", () => {
  it("matches the catalog source, so a reseed never surprises anyone", () => {
    const file = fileURLToPath(new URL("../../../database/catalog-seed.sql", import.meta.url));
    const onDisk = readFileSync(file, "utf8").replaceAll("\r\n", "\n");
    expect(onDisk, "run `npm run seed:sql --workspace=@orbit/kpi-catalog` and commit the result").toBe(seedSql());
  });

  it("is safe to run twice", () => {
    const sql = seedSql();
    expect(sql).toContain("on conflict (key) do update");
    expect(sql).toContain("on conflict (id) do update");
    expect(sql.startsWith("-- Generated by")).toBe(true);
    expect(sql).toContain("begin;");
    expect(sql.trimEnd().endsWith("commit;")).toBe(true);
  });

  it("escapes quotes in text", () => {
    expect(seedSql()).toContain("shareholders'' equity".replace("shareholders", "Shareholders"));
  });
});
